#!/bin/bash

echo "======================================"
echo "  OLIGOTOX REPOSITORY CLEANUP"
echo "  Making repo publish-ready"
echo "======================================"
echo ""

# 1. Create .gitignore if not exists or update it
echo "📝 Updating .gitignore..."
cat > .gitignore << 'GITIGNORE'
# Python
