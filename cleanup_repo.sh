echo "✅ README files created"

# 7. Organize files
echo ""
echo "📦 Organizing repository structure..."

# Ensure all scripts are in proper locations
mkdir -p src/data src/models src/features
mkdir -p notebooks
mkdir -p tests

echo "✅ Directory structure verified"

